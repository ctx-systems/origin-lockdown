#!/usr/bin/env bash
# Print an nginx snippet that restores the real visitor IP from a proxy and
# (optionally) denies anyone who is not that proxy.
#   scripts/nginx-snippet.sh CF-Connecting-IP ips/cloudflare-v4.txt ips/cloudflare-v6.txt > /etc/nginx/conf.d/cloudflare.conf
#   scripts/nginx-snippet.sh --allow-only X-Forwarded-For ips/bunny-cdn-*.txt
set -euo pipefail

allow_only=0
[ "${1:-}" = "--allow-only" ] && { allow_only=1; shift; }
header="${1:?usage: $0 [--allow-only] <real-ip-header> list.txt...}"; shift

echo "# generated by origin-lockdown on $(date -u +%F)"
for f in "$@"; do
  echo "# $(basename "$f")"
  grep -vE '^\s*(#|$)' "$f" | sed 's/.*/set_real_ip_from &;/'
done
echo "real_ip_header $header;"
echo "real_ip_recursive on;"
if [ "$allow_only" = 1 ]; then
  echo
  echo "# NOTE: allow/deny run after real_ip, so match the proxy on the TCP peer instead:"
  echo "geo \$realip_remote_addr \$origin_lockdown_ok {"
  echo "    default 0;"
  for f in "$@"; do grep -vE '^\s*(#|$)' "$f" | sed 's/.*/    & 1;/'; done
  echo "}"
  echo "# then in each server {}:  if (\$origin_lockdown_ok = 0) { return 444; }"
fi
